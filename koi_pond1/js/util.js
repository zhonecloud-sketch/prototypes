// Patch a built-in material's shaders. `vertex`/`fragment` map chunk names to replacement code.
export function patchMaterial(mat, key, { uniforms = {}, vertexHead = '', fragmentHead = '', vertex = {}, fragment = {} }) {
  mat.onBeforeCompile = (shader) => {
    Object.assign(shader.uniforms, uniforms);
    let vs = vertexHead + '\n' + shader.vertexShader;
    let fs = fragmentHead + '\n' + shader.fragmentShader;
    for (const [chunk, code] of Object.entries(vertex)) {
      const tag = `#include <${chunk}>`;
      if (!vs.includes(tag)) console.warn('missing chunk', chunk);
      vs = vs.replace(tag, code);
    }
    for (const [chunk, code] of Object.entries(fragment)) {
      const tag = `#include <${chunk}>`;
      if (!fs.includes(tag)) console.warn('missing chunk', chunk);
      fs = fs.replace(tag, code);
    }
    shader.vertexShader = vs;
    shader.fragmentShader = fs;
  };
  mat.customProgramCacheKey = () => key;
  return mat;
}

